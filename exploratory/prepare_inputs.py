"""Prepare supplementary inputs with an isolated cairn ledger and checks log.

This helper never routes preparation bookkeeping to the published primary
artifacts. Derived input tables are regenerated by the original source scripts.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STEPS = ["10_prepare.py", "20_features.py", "30_labels.py"]


def prepare_inputs(*, with_models=False):
    output = ROOT / "reports/exploratory/preparation"
    output.mkdir(parents=True, exist_ok=True)
    ledger, checks = output / "numbers.json", output / "checks.jsonl"
    for path in [ledger, checks]:
        if not path.resolve().is_relative_to(output.resolve()):
            raise ValueError("supplementary bookkeeping escapes its output directory")
        if path.resolve().is_relative_to((ROOT / "artifacts").resolve()):
            raise ValueError("refusing primary artifact bookkeeping paths")
    env = dict(os.environ, CAIRN_LEDGER=str(ledger), CAIRN_CHECKS=str(checks))
    steps = [*STEPS]
    if with_models:
        if not (ROOT / "scripts/40_model.py").exists():
            raise ValueError("model preparation is not available for this project")
        steps.append("40_model.py")
    for step in steps:
        subprocess.run(
            [sys.executable, str(ROOT / "scripts" / step)], cwd=ROOT, env=env, check=True
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--with-models",
        action="store_true",
        help="also regenerate recorded model OOF inputs (analysis machine only)",
    )
    args = parser.parse_args()
    prepare_inputs(with_models=args.with_models)


if __name__ == "__main__":
    main()
